"""Write Tables S6 and S7 (baseline characteristics, missingness) for the JAC-AMR supplement.

Reads the outputs of scripts/fq_baseline.py in results/full and rounds once, here.
Run from the repository root:  python -m scripts.fq_baseline_tex
"""
import json

import pandas as pd
import os

os.makedirs("outputs/figures", exist_ok=True)
os.makedirs("outputs/tables", exist_ok=True)

R = "results/full/"
tab = pd.read_csv(R + "fq_baseline_characteristics.csv")
miss = pd.read_csv(R + "fq_missingness.csv")
summ = json.load(open(R + "fq_baseline_summary.json"))
n1, n = summ["n_exposed"], summ["n_orders"]
n0 = n - n1
assert (n1, n0) == (4646, 28078)

ORG = {"ESCHERICHIA COLI": r"\textit{Escherichia coli}",
       "KLEBSIELLA PNEUMONIAE": r"\textit{Klebsiella pneumoniae}",
       "ENTEROCOCCUS SPECIES": r"\textit{Enterococcus} species",
       "MUCOID PSEUDOMONAS AERUGINOSA": r"\textit{Pseudomonas aeruginosa}, mucoid",
       "STAPHYLOCOCCUS AUREUS": r"\textit{Staphylococcus aureus}",
       "PSEUDOMONAS AERUGINOSA": r"\textit{Pseudomonas aeruginosa}",
       "Other": "Other organisms"}
SPEC = {"URINE": "Urine", "RESPIRATORY": "Respiratory", "BLOOD": "Blood"}
AGE = {"above 90": "90 or older"}


def g(x):
    return f"{int(round(x)):,}"


def d(x):
    "A signed SMD with a typeset minus and no negative zero."
    t = f"{x:.2f}"
    return "0.00" if t == "-0.00" else t.replace("-", "$-$")


def pct(x):
    return "$<$0.1" if 0 < x < 0.05 else f"{x:.1f}"


def binrow(r):
    return (f"{g(r.exposed_n)} ({r.exposed_pct:.1f}) & {g(r.unexposed_n)} "
            f"({r.unexposed_pct:.1f}) & {d(r.smd_unweighted)} & {d(r.smd_weighted)}")


def numrow(r):
    def q(p):
        return (f"{r[p + '_median']:.0f} ({r[p + '_q1']:.0f}--{r[p + '_q3']:.0f})")
    return f"{q('exposed')} & {q('unexposed')} & {d(r.smd_unweighted)} & {d(r.smd_weighted)}"


def get(section, label):
    hit = tab[(tab.section == section) & (tab.label == label)]
    assert len(hit) == 1, (section, label)
    return hit.iloc[0]


lines = []


def head(text):
    lines.append(r"\multicolumn{5}{l}{\itshape " + text + r"} \\")


def row(label, body, indent=True):
    lines.append((r"\quad " if indent else "") + label + " & " + body + r" \\")


head("Age, years")
for _, r in tab[tab.section == "Age, years"].iterrows():
    row(AGE.get(r.label, r.label.replace(" years", "").replace("-", "--")), binrow(r))
row("Sex coded 1$^{a}$", binrow(get("Demographics", "Gender coded 1")), indent=False)
head("Care setting of the index culture")
for lab in ("Inpatient", "Outpatient", "Not recorded"):
    row(f"{lab} order" if lab != "Not recorded" else "Ordering mode not recorded",
        binrow(get("Ordering mode", lab)))
row("Emergency department", binrow(get("Setting of the index culture", "Emergency department")))
row("Intensive care", binrow(get("Setting of the index culture", "Intensive care")))
row("Nursing home visit", binrow(get("Setting of the index culture", "Nursing home visit")))
head("Specimen")
for _, r in tab[tab.section == "Specimen"].iterrows():
    row(SPEC[r.label], binrow(r))
head("Organism$^{b}$")
for _, r in tab[tab.section == "Organism (analysed row)"].iterrows():
    row(ORG[r.label], binrow(r))
head("History and deprivation, median (IQR)")
for _, r in tab[tab.section == "History and deprivation"].iterrows():
    row(r.label.replace(", n", ""), numrow(r))

fu = summ["followup_days"]
head("Follow-up to the outcome culture")


def fq(k):
    d = fu[k]
    return f"{d['median']:.0f} ({d['q1']:.0f}--{d['q3']:.0f})"


row("Days, median (IQR)", f"{fq('exposed')} & {fq('unexposed')} & & ")
for w in ("30", "90"):
    e, u = fu["exposed"][f"within_{w}"], fu["unexposed"][f"within_{w}"]
    row(f"Within {w} days, \\%", f"{100 * e:.1f} & {100 * u:.1f} & & ")

with open("outputs/tables/supp_tab_baseline.tex", "w") as f:
    f.write("% Generated by scripts/fq_baseline_tex.py from results/full; do not edit.\n")
    f.write("\n".join(lines) + "\n")

NAMES = {"wbc": "White cell count", "cr": "Creatinine", "lactate": "Lactate",
         "plt": "Platelets", "bun": "Urea nitrogen", "heartrate": "Heart rate",
         "resprate": "Respiratory rate", "temp": "Temperature", "sysbp": "Systolic blood pressure"}
HANDLING = {"missing category": "Explicit missing level",
            "coded 0": "Coded 0",
            "all indicators 0": "All setting indicators 0",
            "training-period median": "Training-period median"}
mlines = []
for _, r in miss.iterrows():
    v = r.variable.strip()
    indent = r.variable.startswith(" ")
    label = NAMES.get(v, v)
    if label.startswith("Any acute"):
        label = "Any acute laboratory or vital sign$^{c}$"
    if label == "Gender":
        label = "Sex"
    if indent:
        label = r"\quad " + label
    mlines.append(f"{label} & {g(r.missing_n)} ({pct(r.missing_pct)}) & {g(r.missing_exposed)} & "
                  f"{g(r.missing_unexposed)} & {HANDLING[r.handling]} \\\\")
with open("outputs/tables/supp_tab_missing.tex", "w") as f:
    f.write("% Generated by scripts/fq_baseline_tex.py from results/full; do not edit.\n")
    f.write("\n".join(mlines) + "\n")
print("\n".join(lines))
print("\n".join(mlines))
